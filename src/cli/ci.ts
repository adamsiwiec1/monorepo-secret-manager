import { spawnSync } from "child_process";
import fs from "fs";
import path from "path";
import { Provider } from "../types";

/** Repo secrets each provider's auth step reads. Values are never printed. */
export const CI_SECRETS: Record<Provider, string[]> = {
  gcp: ["WIF_PROVIDER", "WIF_SERVICE_ACCOUNT"],
  aws: ["AWS_ROLE_ARN"],
  azure: ["AZURE_CLIENT_ID", "AZURE_TENANT_ID", "AZURE_SUBSCRIPTION_ID"],
  local: [],
};

const SDK: Record<Provider, string> = {
  gcp: "@google-cloud/secret-manager",
  aws: "@aws-sdk/client-secrets-manager",
  azure: "@azure/identity @azure/keyvault-secrets",
  local: "",
};

function authStep(provider: Provider, region?: string): string {
  switch (provider) {
    case "gcp":
      return `      - uses: google-github-actions/auth@v2
        with:
          workload_identity_provider: \${{ secrets.WIF_PROVIDER }}
          service_account: \${{ secrets.WIF_SERVICE_ACCOUNT }}`;
    case "aws":
      return `      - uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: \${{ secrets.AWS_ROLE_ARN }}
          aws-region: ${region || "us-east-1"}`;
    case "azure":
      return `      - uses: azure/login@v2
        with:
          client-id: \${{ secrets.AZURE_CLIENT_ID }}
          tenant-id: \${{ secrets.AZURE_TENANT_ID }}
          subscription-id: \${{ secrets.AZURE_SUBSCRIPTION_ID }}`;
    default:
      throw new Error("The local store is gitignored, so CI can't read it. Use gcp, aws, or azure for CI envs.");
  }
}

export interface WorkflowSpec {
  env: string;
  service: string;
  provider: Provider;
  region?: string;
  config: string;
}

export function renderWorkflow(spec: WorkflowSpec): string {
  const target = spec.service === "all" ? "" : ` ${spec.service}`;
  const configFlag = spec.config === ".secrets-config" ? "" : ` --config ${spec.config}`;
  return `# Generated by \`msm ci setup\`. Safe to edit; rerun to regenerate.
name: msm secrets

on:
  push:
    branches: [main, master]
  pull_request:
  workflow_dispatch:

permissions:
  contents: read
  id-token: write

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
${authStep(spec.provider, spec.region)}
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: npm install -g monorepo-secret-manager ${SDK[spec.provider]}
      - run: msm export${target} -e ${spec.env} --format github --ambient-creds${configFlag}
      # Secrets are now env vars for the steps below. Add your build here.
      - run: echo "secrets loaded for ${spec.env}"
`;
}

export interface GhRunner {
  /** Run gh with args; stdin is piped when given. Returns exit code and stdout. */
  (args: string[], input?: string): { status: number; stdout: string };
}

export const runGh: GhRunner = (args, input) => {
  const res = spawnSync("gh", args, { input, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
  if (res.error) return { status: 127, stdout: "" };
  return { status: res.status ?? 1, stdout: res.stdout || "" };
};

/** Throw a clear error when gh is missing or logged out. */
export function requireGh(gh: GhRunner): void {
  if (gh(["--version"]).status === 127) {
    throw new Error("gh is not installed. Get it at https://cli.github.com, then run 'gh auth login'.");
  }
  if (gh(["auth", "status"]).status !== 0) {
    throw new Error("gh is not logged in. Run 'gh auth login'.");
  }
}

/** Write the workflow only when it changed. Returns what happened. */
export function writeWorkflow(file: string, body: string, dryRun: boolean): "created" | "updated" | "unchanged" {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;
  if (existing === body) return "unchanged";
  if (!dryRun) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
  }
  return existing === undefined ? "created" : "updated";
}
